create table if not exists public.seo_blocks (
	id bigserial primary key,
	entity_type text not null check (entity_type in ('country', 'city', 'city_category')),
	entity_id text not null,
	h2 text not null,
	body text not null,
	is_active boolean not null default true,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	unique (entity_type, entity_id)
);

create index if not exists seo_blocks_active_lookup_idx
	on public.seo_blocks (entity_type, entity_id)
	where is_active = true;

insert into public.seo_blocks (entity_type, entity_id, h2, body)
select
	'country',
	c.id::text,
	'Экскурсии по России: как выбрать маршрут',
	'Россия объединяет города с очень разным характером: от музейных прогулок и исторических кварталов до природных маршрутов, гастрономии и авторских экскурсий. Используйте страницу страны как отправную точку: сравните популярные города, посмотрите количество экскурсий и выберите направление под формат поездки.'
from public.countries c
where lower(regexp_replace(trim(trailing '/' from c.url), '^.*/', '')) = 'russia'
on conflict (entity_type, entity_id) do update set
	h2 = excluded.h2,
	body = excluded.body,
	is_active = true,
	updated_at = now();

